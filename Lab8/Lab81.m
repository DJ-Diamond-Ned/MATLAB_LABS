clear;       % Очищает память от всех старых переменных
clc;         % Чистит командное окно (экран), чтобы было пусто и красиво
close all;   % Закрывает все открытые окна с графиками

%% 1. ИСХОДНЫЕ ДАННЫЕ
% t - это время (в твоем задании это ось X)
t = [5, 6, 7, 8, 10, 11, 12, 13, 14]; 
% y - это координаты местоположения колонны в это время
y = [347.6, 205.1, 173.5, 4.008, 38.54, 92.25, 273.63, 550.10, 650.19];
% p - веса (степень доверия разведчикам). 1.0 - верю полностью, 0.3 - сомневаюсь
p = [0.9, 0.8, 0.7, 0.5, 0.9, 1, 0.7, 0.8, 0.3];

% Точка времени, в которую майор Громов должен бахнуть (из условия задания)
t_target = 9;

% Считаем количество экспериментальных точек
n = length(t);

fprintf('--- РАСЧЕТ ДЛЯ МАЙОРА ГРОМОВА ---\n');

%% 2. ВЫБОР МОДЕЛИ
% Степень 2 означает полином вида: a*t^2 + b*t + c (парабола)
deg = 2; 
fprintf('Выбрана степень полинома: %d\n\n', deg);

%% 3. МЕТОД 1: МАТРИЦА ВАНДЕРМОНДА (Классический подход)
fprintf('Метод Вандермонда:\n');
% Создаем пустую таблицу (матрицу), куда будем записывать степени t
V = zeros(n, deg+1); 
for i = 1:n
    for j = 0:deg
        V(i, j+1) = t(i)^j; % Заполняем столбцы: t^0 (единицы), t^1, t^2
    end
end
% Находим коэффициенты полинома (a, b, c), решая систему уравнений V*a = y
a_vand = V \ y'; 

% Считаем прогноз для t=9 по формуле: y = c + b*t + a*t^2
y_res_vand = 0;
for j = 0:deg
    y_res_vand = y_res_vand + a_vand(j+1) * t_target^j;
end
fprintf('Координата для залпа (t=9): %.4f\n\n', y_res_vand);

%% 4. МЕТОД 2: POLYFIT (Стандартная функция Matlab)
fprintf('Метод polyfit:\n');
% Встроенная функция Matlab, которая сама находит коэффициенты полинома
coeffs_poly = polyfit(t, y, deg);
% Считаем значение в точке 9, используя найденные коэффициенты
y_res_poly = polyval(coeffs_poly, t_target);
fprintf('Координата для залпа (t=9): %.4f\n\n', y_res_poly);

%% 5. МЕТОД 3: FMINSEARCH (С учетом весов "p")
fprintf('Метод fminsearch (с весами):\n');

% Настройка: увеличиваем лимиты, чтобы алгоритм не сдался раньше времени
options = optimset('MaxFunEvals', 10000, 'MaxIter', 10000);

% Анонимная функция ошибки (целевая функция): 
% Мы считаем разницу между моделью и реальными y, возводим в квадрат и умножаем на вес p
weighted_err = @(c) sum(p .* (polyval(c, t) - y).^2);

% В качестве подсказки (стартовой точки) даем коэффициенты из обычного polyfit
c_start = polyfit(t, y, deg); 

% fminsearch ищет такие коэффициенты "c", при которых ошибка weighted_err будет минимальной
coeffs_weighted = fminsearch(weighted_err, c_start, options);

% Считаем итоговый прогноз
y_res_weighted = polyval(coeffs_weighted, t_target);
fprintf('Координата для залпа (t=9): %.4f\n\n', y_res_weighted);

%% 6. ОЦЕНКА ТОЧНОСТИ (Среднеквадратичная ошибка - RMSE)
% Функция для расчета RMSE: корень из среднего квадрата отклонений
rmse_calc = @(y_model) sqrt(mean((y_model - y).^2));

fprintf('Оценка точности (RMSE):\n');
% Считаем RMSE для каждого метода, сравнивая предсказанные y с реальными
fprintf('Вандермонд: %.4f\n', rmse_calc(polyval(flip(a_vand'), t)));
fprintf('Polyfit:    %.4f\n', rmse_calc(polyval(coeffs_poly, t)));
fprintf('С весами:   %.4f\n\n', rmse_calc(polyval(coeffs_weighted, t)));

%% 7. ПОСТРОЕНИЕ ГРАФИКА
% Создаем плотную сетку времени (100 точек) для плавного графика
t_plot = linspace(min(t), max(t), 100);
% Считаем значения y для этой сетки по нашей лучшей модели
y_plot_fit = polyval(coeffs_weighted, t_plot);

figure('Color', 'w'); % Создаем окно графика с белым фоном
hold on; grid on;     % Будем рисовать несколько графиков на одном и включим сетку

% Рисуем исходные точки. 1./p*10 — это визуализация погрешности (усы)
errorbar(t, y, 1./p*10, 'ko', 'MarkerFaceColor', 'k', 'DisplayName', 'Данные разведки'); 

% Рисуем плавную линию нашей модели (красным цветом)
plot(t_plot, y_plot_fit, 'r-', 'LineWidth', 2, 'DisplayName', 'Траектория (модель)');

% Рисуем синий квадрат в точке нашего залпа (t=9)
plot(t_target, y_res_weighted, 'bs', 'MarkerSize', 12, 'LineWidth', 2, 'DisplayName', 'Точка залпа (t=9)');

% Подписываем оси и заголовок
xlabel('Время (t)');
ylabel('Положение колонны (y)');
title('Расчет точки артобстрела');
legend('Location', 'northeast'); % Показываем легенду (список линий)

% Добавляем текстовую метку с результатом прямо на график
text(t_target+0.2, y_res_weighted, sprintf('Y = %.2f', y_res_weighted), 'Color', 'blue', 'FontWeight', 'bold');

fprintf('РЕКОМЕНДАЦИЯ: Огонь по координате y = %.2f\n', y_res_weighted);