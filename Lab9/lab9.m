clear; clc; close all; 

    % ЧАСТЬ 1: ЧИСЛЕННОЕ ДИФФЕРЕНЦИРОВАНИЕ ФУНКЦИИ 
    % Задаем исследуемую функцию через анонимную функцию @(x)
    f = @(x) sin(x-1) - x.^3 .* cos(x); 
    x0 = 0.6; % Точка исследования по заданию

    % --- АНАЛИТИЧЕСКИЙ РАСЧЕТ (ТОЧНЫЕ ЗНАЧЕНИЯ) ---
    % Считаем 1-ю производную вручную для контроля точности
    y1_exact = cos(x0-1) - 3*x0^2*cos(x0) + x0^3*sin(x0);
    % Считаем 2-ю производную вручную для контроля точности
    y2_exact = -sin(x0-1) - 6*x0*cos(x0) + 6*x0^2*sin(x0) + x0^3*cos(x0);

    % Выводим эталонные значения в командное окно
    fprintf('Точные значения в x=0.6: y'' = %.8f, y'''' = %.8f\n\n', y1_exact, y2_exact);

    % --- ИССЛЕДОВАНИЕ ЗАВИСИМОСТИ ОТ ШАГА h ---
    % Создаем вектор из 40 значений шага h от 0.1 до 10^-7
    h = logspace(-1, -7, 40); 
    err1_central = zeros(size(h)); % Пустой массив для ошибок 1-й произв. (простая)
    err1_4point = zeros(size(h));  % Пустой массив для ошибок 1-й произв. (сложная)
    err2_simple = zeros(size(h));  % Пустой массив для ошибок 2-й произв. (простая)
    err2_5point = zeros(size(h));  % Пустой массив для ошибок 2-й произв. (сложная)

    % Запускаем цикл расчетов для каждого значения h
    for i = 1:length(h)
        hi = h(i); % Берем текущий шаг из вектора

        % Численная 1-я производная: центральная разность O(h^2)
        y1_central = (f(x0+hi) - f(x0-hi))/(2*hi); 
        % Численная 1-я производная: многоточечная формула O(h^4)
        y1_4point = (-f(x0+2*hi) + 8*f(x0+hi) - 8*f(x0-hi) + f(x0-2*hi))/(12*hi);
        
        % Считаем модули ошибок для первой производной
        err1_central(i) = abs(y1_central - y1_exact);
        err1_4point(i) = abs(y1_4point - y1_exact);

        % Численная 2-я производная: простая формула O(h^2)
        y2_simple = (f(x0+hi) - 2*f(x0) + f(x0-hi))/hi^2;
        % Численная 2-я производная: многоточечная формула O(h^4)
        y2_5point = (-f(x0+2*hi) + 16*f(x0+hi) - 30*f(x0) + 16*f(x0-hi) - f(x0-2*hi))/(12*hi^2);
        
        % Считаем модули ошибок для второй производной
        err2_simple(i) = abs(y2_simple - y2_exact);
        err2_5point(i) = abs(y2_5point - y2_exact);
    end

    % --- ВЫВОД РЕЗУЛЬТАТОВ ДЛЯ КОНКРЕТНОГО ШАГА h=0.01 ---
    [~, idx] = min(abs(h - 0.01)); % Ищем в векторе индекс значения, близкого к 0.01
    fprintf('Результаты при h=0.01:\n');
    fprintf('  1-я производная (центральная): %.8f, ошибка = %.2e\n', ...
        (f(x0+0.01)-f(x0-0.01))/(0.02), err1_central(idx));
    fprintf('  1-я производная (многоточечная): %.8f, ошибка = %.2e\n', ...
        (-f(x0+0.02)+8*f(x0+0.01)-8*f(x0-0.01)+f(x0-0.02))/(0.12), err1_4point(idx));
    fprintf('  2-я производная (простая): %.8f, ошибка = %.2e\n', ...
        (f(x0+0.01)-2*f(x0)+f(x0-0.01))/0.0001, err2_simple(idx));
    fprintf('  2-я производная (многоточечная): %.8f, ошибка = %.2e\n\n', ...
        (-f(x0+0.02)+16*f(x0+0.01)-30*f(x0)+16*f(x0-0.01)-f(x0-0.02))/(12*0.0001), err2_5point(idx));

    % --- ПОСТРОЕНИЕ ПЕРВОГО ОКНА ГРАФИКОВ ---
    figure('Position', [100, 100, 1000, 800]);

    subplot(2,2,1); % Левый верхний график
    loglog(h, err1_central, 'b-^', h, err1_4point, 'r-s', 'LineWidth', 1.5); % Логарифмический масштаб
    xlabel('Шаг h'); ylabel('Погрешность'); title('1-я производная (анализ)');
    legend('O(h^2)', 'O(h^4)', 'Location','southeast'); grid on; % Легенда и сетка

    subplot(2,2,2); % Правый верхний график
    loglog(h, err2_simple, 'b-^', h, err2_5point, 'r-s', 'LineWidth', 1.5);
    xlabel('Шаг h'); ylabel('Погрешность'); title('2-я производная (анализ)');
    legend('O(h^2)', 'O(h^4)', 'Location','southeast'); grid on;

    subplot(2,2,3); % Левый нижний график
    loglog(h, err1_central, 'b-', h, err1_4point, 'r-', 'LineWidth', 1.5);
    [~, opt_idx] = min(err1_4point); % Находим точку самого точного шага
    hold on; plot(h(opt_idx), err1_4point(opt_idx), 'ro', 'MarkerSize', 10); % Рисуем красный кружок
    xlabel('Шаг h'); ylabel('Погрешность'); title('Поиск оптимального шага');
    legend('Центральная', 'Многоточечная', 'Оптимум', 'Location','southeast'); grid on;

    subplot(2,2,4); % Правый нижний график
    xx = linspace(0, 1.2, 300); % Сетка для рисования плавной кривой
    yy1 = cos(xx-1) - 3.*xx.^2.*cos(xx) + xx.^3.*sin(xx); % Считаем значения производной
    plot(xx, yy1, 'b-', 'LineWidth', 1.5); hold on; % Рисуем саму производную
    plot(x0, y1_exact, 'ro', 'MarkerSize', 10); % Ставим точку x=0.6 на графике
    xlabel('x'); ylabel('y'''); title('График 1-й производной (аналитика)'); grid on;
    legend('y''(x)', 'Точка x=0.6', 'Location','best');


    % ЧАСТЬ 2: ДИФФЕРЕНЦИРОВАНИЕ ТАБЛИЧНОЙ ФУНКЦИИ (АРТОБСТРЕЛ)
    x_tab = [5, 6, 7, 8, 10, 11, 12, 13, 14]; % Время t из твоего варианта
    y_tab = [347.6, 205.1, 173.5, 4.008, 38.54, 92.25, 273.63, 550.10, 650.19]; % Твои координаты y

    % Точка посередине между 8 и 9 узлами (между t=13 и t=14)
    x_between = (x_tab(8) + x_tab(9)) / 2; % Получится 13.5

    % Строим интерполяционный полином Лагранжа (степень 8)
    % mu нужно для масштабирования, чтобы Matlab не ругался на точность
    [p, S, mu] = polyfit(x_tab, y_tab, 8); 

    % Находим производные от коэффициентов полинома функцией polyder
    p1 = polyder(p); % Коэффициенты для первой производной
    p2 = polyder(p1); % Коэффициенты для второй производной

    % Считаем значения производных в точке (scaled учитывает mu)
    x_scaled = (x_between - mu(1)) / mu(2); % Пересчитываем x под масштаб mu
    y1_between = (1/mu(2)) * polyval(p1, x_scaled); % Умножаем на 1/mu для корректности
    y2_between = (1/mu(2)^2) * polyval(p2, x_scaled); % Умножаем на 1/mu^2 для корректности

    % Выводим результаты в консоль
    fprintf('Точка между узлами 8 и 9: t = %.4f\n', x_between);
    fprintf('1-я производная (скорость): %.6f\n', y1_between);
    fprintf('2-я производная (ускорение): %.6f\n', y2_between);

    % Оценка теоретической погрешности по формуле (13.25)
    h_step = x_tab(9) - x_tab(8); % Считаем шаг между узлами
    diff9 = diff(y_tab, 8); % Берем конечную разность максимально возможного порядка
    f_n1 = diff9(end) / h_step^8; % Приближенно оцениваем производную высокого порядка
    omega_val = prod(x_between - x_tab); % Считаем произведение (x-x0)*(x-x1)...
    error_estimate = abs(f_n1 / factorial(9) * omega_val); % Финальная формула погрешности
    fprintf('Оценка погрешности 1-й производной: %.4e\n', error_estimate);

    % --- ПОСТРОЕНИЕ ВТОРОГО ОКНА ГРАФИКОВ ---
    figure('Position', [100, 100, 1000, 400]);

    xx_tab = linspace(5, 14, 500); % Сетка для плавного графика по t
    xx_scaled = (xx_tab - mu(1)) / mu(2); % Учет масштабирования
    yy_tab = polyval(p, xx_scaled); % Значения полинома

    subplot(1,2,1); % Левый график (Интерполяция)
    plot(xx_tab, yy_tab, 'b-', 'LineWidth', 1.5); hold on;
    plot(x_tab, y_tab, 'ro', 'MarkerSize', 8); % Рисуем исходные точки
    plot(x_between, polyval(p, (x_between - mu(1))/mu(2)), 'gs', 'MarkerSize', 10, 'MarkerFaceColor', 'g');
    xlabel('t (Время)'); ylabel('y (Координата)'); title('Интерполяция маршрута'); grid on;
    legend('Полином', 'Узлы', 'Точка t=13.5', 'Location','best');

    subplot(1,2,2); % Правый график (Производная)
    yy1_tab = (1/mu(2)) * polyval(p1, xx_scaled); % Значения первой производной
    plot(xx_tab, yy1_tab, 'r-', 'LineWidth', 1.5); hold on;
    plot(x_between, y1_between, 'bo', 'MarkerSize', 10, 'MarkerFaceColor', 'b');
    xlabel('t (Время)'); ylabel('y'' (Скорость)'); title('Первая производная траектории'); grid on;
    legend('y''(t)', 'y''(13.5)', 'Location','best');

    % Дополнительный расчет для точки между 1 и 2 узлами (t=5.5)
    x_between_12 = (x_tab(1) + x_tab(2)) / 2; % Центр первого интервала
    x_scaled_12 = (x_between_12 - mu(1)) / mu(2); % Масштаб
    y1_between_12 = (1/mu(2)) * polyval(p1, x_scaled_12); % Первая производная в 5.5
    y2_between_12 = (1/mu(2)^2) * polyval(p2, x_scaled_12); % Вторая производная в 5.5

    % Погрешность для первой точки (5.5)
    omega_val_12 = prod(x_between_12 - x_tab);
        error_estimate_12 = abs(f_n1 / factorial(9) * omega_val_12);

    % Финальный вывод в консоль
    fprintf('\nТочка между узлами 1 и 2 (t=%.4f)\n', x_between_12);
    fprintf('1-я производная: %.6f, погрешность: %.4e\n', y1_between_12, error_estimate_12);
    fprintf('2-я производная: %.6f\n', y2_between_12);